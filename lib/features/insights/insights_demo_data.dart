  static List<AnalyticsMetric> metrics({
    required int periodDays,
    required String platform,
    required String contentType,
  }) {
    final platformFactor = platform == 'Instagram' ? 0.6 : 0.4;
    final periodFactor = periodDays / 7;
    final contentFactor = contentType == 'Reels' ? 1 : 0.84;
    final factor = platformFactor * periodFactor * contentFactor;

    return [
      AnalyticsMetric(
        title: 'Tayangan',
        value: _formatInteger(28420 * factor),
        description: 'Penayangan per hari',
        axisLabels: const ['6 rb', '3 rb', '0'],
        points: [3.1, 3.5, 3.5, 4.7, 3.9, 4.3, 5.0],
      ),
      AnalyticsMetric(
        title: 'Interaksi',
        value: _formatInteger(2360 * factor),
        description: 'Interaksi per hari',
        axisLabels: const ['600', '300', '0'],
        points: [2.4, 2.8, 2.6, 3.8, 3.1, 3.6, 4.1],
      ),
      AnalyticsMetric(
        title: 'Tingkat interaksi',
        value: '${(8.3 * contentFactor).toStringAsFixed(1)}%',
        description: 'Interaksi ÷ tayangan (%)',
        axisLabels: const ['10%', '8%', '6%'],
        points: [3.0, 3.0, 2.7, 3.0, 3.0, 3.2, 3.15],
      ),
      AnalyticsMetric(
        title: 'Rata-rata jangkauan per unggahan',
        value: _formatInteger(1842 * platformFactor * contentFactor),
        description: 'Rata-rata akun per postingan',
        axisLabels: const ['3 rb', '1,5 rb', '0'],
        points: [2.0, 2.2, 2.3, 2.5, 2.6, 2.9, 3.3],
      ),
    ];
  }

  static String _formatInteger(double value) => value
      .round()
      .toString()
      .replaceAllMapped(RegExp(r'\B(?=(\d{3})+(?!\d))'), (match) => '.');
}
